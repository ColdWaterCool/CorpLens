def join_multi(items: list[str], empty: str = "（未选）") -> str:
    items = [x for x in items if x]
    return "、".join(items) if items else empty


def compose_location(city: str, scene: str) -> str:
    parts = [p for p in [city, scene] if p]
    return " · ".join(parts) if parts else ""


